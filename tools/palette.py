#!/usr/bin/env python3
"""BakaBot palette source and semantic token generator.

The palette source is tools/palette.json. Everything else is derived here so
GTK3, GTK4, legacy GTK, assets, and window buttons receive the same literals.
"""

from __future__ import annotations

import colorsys
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE_FILE = ROOT / "tools" / "palette.json"
TOKENS_SCSS = ROOT / "gtk-3.20" / "_bakabot-colors.scss"


def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.strip().lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    if len(value) != 6:
        raise ValueError(f"invalid hex color: {value!r}")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))


def rgb_to_hex(rgb: tuple[int, int, int]) -> str:
    return "#%02x%02x%02x" % rgb


def rgb_to_hsv(rgb: tuple[int, int, int]) -> tuple[float, float, float]:
    r, g, b = (c / 255 for c in rgb)
    return colorsys.rgb_to_hsv(r, g, b)


def hsv_to_rgb(h: float, s: float, v: float) -> tuple[int, int, int]:
    r, g, b = colorsys.hsv_to_rgb(h, s, v)
    return (round(r * 255), round(g * 255), round(b * 255))


def adjust_lightness(value: str, delta: float) -> str:
    r, g, b = hex_to_rgb(value)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    l = min(1.0, max(0.0, l + delta))
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return rgb_to_hex((round(r * 255), round(g * 255), round(b * 255)))


def mix(value: str, other: str, weight: float) -> str:
    a = hex_to_rgb(value)
    b = hex_to_rgb(other)
    return rgb_to_hex(tuple(round(a[i] * (1 - weight) + b[i] * weight) for i in range(3)))


def rgba(value: str, alpha: float) -> str:
    r, g, b = hex_to_rgb(value)
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def load_palette() -> dict:
    with PALETTE_FILE.open() as handle:
        return json.load(handle)


def derive_tokens() -> dict[str, str]:
    palette = load_palette()
    base = {name: value for name, value in palette["base"].items()}
    roles = palette["roles"]
    derive = palette["derive"]
    overrides = palette.get("overrides", {})

    def role(name: str) -> str:
        return base[roles[name]]

    primary = role("primary")
    secondary = role("secondary")
    surface = role("surface")
    text = role("text")
    white = base["white"]

    primary_dark = adjust_lightness(primary, -float(derive["primary_darken"]))
    primary_light = adjust_lightness(primary, float(derive["primary_lighten"]))
    secondary_hover = overrides.get(
        "secondary_hover",
        adjust_lightness(secondary, float(derive["secondary_hover_lighten"])),
    )
    secondary_light = overrides.get(
        "secondary_light",
        mix(secondary, white, float(derive["secondary_light_mix"])),
    )

    tokens = {
        # Raw palette
        "pink": primary,
        "cyan": secondary,
        "red": role("error"),
        "orange": role("warning"),
        "yellow": role("warning_alt"),
        "bg": role("background"),
        "surface": surface,
        "fg": text,
        "white": white,

        # Semantic roles
        "primary": primary,
        "primary_dark": primary_dark,
        "primary_light": primary_light,
        "on_primary": role("on_primary"),
        "secondary": secondary,
        "secondary_hover": secondary_hover,
        "secondary_light": secondary_light,
        "error": role("error"),
        "warning": role("warning"),
        "warning_alt": role("warning_alt"),
        "success": role("success"),
        "background": role("background"),
        "surface": surface,
        "text": text,
        "panel_bg_color": role("panel_bg"),
        "panel_fg_color": role("panel_fg"),

        # Composed tokens
        "selection_bg": rgba(primary, float(derive["selection_alpha"])),
        "selection_bg_backdrop": rgba(
            primary, float(derive["backdrop_selection_alpha"])
        ),
        "link": secondary,
        "link_visited": rgba(secondary, float(derive["link_visited_alpha"])),
        "primary_border": rgba(
            primary_dark, float(derive["primary_border_alpha"])
        ),
    }
    return tokens


_CACHED_TOKENS: dict[str, str] | None = None


def tokens() -> dict[str, str]:
    global _CACHED_TOKENS
    if _CACHED_TOKENS is None:
        _CACHED_TOKENS = derive_tokens()
    return _CACHED_TOKENS


def get_rgb(name: str) -> tuple[int, int, int]:
    return hex_to_rgb(tokens()[name])


def get_hsv(name: str) -> tuple[float, float, float]:
    return rgb_to_hsv(get_rgb(name))


def write_scss(path: Path = TOKENS_SCSS) -> None:
    value = tokens()
    lines = [
        "// Generated by tools/palette.py from tools/palette.json.",
        "// Do not edit by hand; run ./tools/build.sh instead.",
        "",
    ]
    for name in [
        "pink",
        "cyan",
        "red",
        "orange",
        "yellow",
        "bg",
        "surface",
        "fg",
        "white",
        "primary",
        "primary_dark",
        "primary_light",
        "on_primary",
        "secondary",
        "secondary_hover",
        "secondary_light",
        "error",
        "warning",
        "warning_alt",
        "success",
        "background",
        "panel_bg_color",
        "panel_fg_color",
        "selection_bg",
        "selection_bg_backdrop",
        "link",
        "link_visited",
        "primary_border",
    ]:
        lines.append(f"${name}: {value[name]};")
    lines.append("")
    path.write_text("\n".join(lines))


def main() -> int:
    write_scss()
    print(f"Generated {TOKENS_SCSS.relative_to(ROOT)} from tools/palette.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
